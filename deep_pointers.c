#include <stdio.h>

// Пример 1: Функция, меняющая местами значения двух переменных
void swap(int *a, int *b) {
    // В temp мы кладем ЗНАЧЕНИЕ (*), которое лежит по адресу a
    int temp = *a; 
    
    // По адресу a мы записываем ЗНАЧЕНИЕ (*), которое лежит по адресу b
    *a = *b;       
    
    // По адресу b мы записываем сохраненное ЗНАЧЕНИЕ из temp
    *b = temp;     
}

int main() {
    printf("=== ПРИМЕР 1: Обмен значений (Swap) ===\n");
    int x = 100;
    int y = 200;
    
    printf("До вызова swap: x = %d, y = %d\n", x, y);
    // Передаем АДРЕСА (&) переменных, а не сами числа 100 и 200
    swap(&x, &y);
    printf("После вызова swap: x = %d, y = %d\n\n", x, y);


    printf("=== ПРИМЕР 2: Массивы — это скрытые указатели ===\n");
    int numbers[3] = {10, 20, 30};

    // В языке C имя массива само по себе является указателем на его первый элемент!
    printf("Где лежит массив (адрес numbers): %p\n", numbers);
    printf("Где лежит первый элемент (&numbers[0]): %p\n", &numbers[0]);
    // Как видишь, адреса абсолютно одинаковые.


    printf("\n=== ПРИМЕР 3: Арифметика указателей ===\n");
    // Что если к указателю прибавить 1? 
    // Поскольку numbers - это массив типа int (каждый элемент занимает 4 байта),
    // компилятор сам знает, что "+1" означает "сдвинься на 4 байта вперед".

    printf("Элемент 0 (через *numbers): %d\n", *numbers);
    
    // Сдвигаемся на одну "ячейку типа int" вперед и берем оттуда значение
    printf("Элемент 1 (через *(numbers + 1)): %d\n", *(numbers + 1));
    
    // Сдвигаемся на две ячейки вперед
    printf("Элемент 2 (через *(numbers + 2)): %d\n", *(numbers + 2));

    // На самом деле запись numbers[1] — это просто визуальная "обертка"
    // над арифметикой указателей *(numbers + 1). Компилятор переводит скобки [] именно так!

    return 0;
}