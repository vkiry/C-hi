#include <stdio.h>

int main() {
    int number;

    printf("Введите целое число от 1 до 10: ");
    scanf("%d", &number);

    // 1. Условный оператор if-else
    if (number < 1 || number > 10) {
        // Если число меньше 1 ИЛИ больше 10
        printf("Ошибка: число вне диапазона!\n");
        // Завершаем программу с кодом 1 (стандартный код ошибки в консоли)
        return 1; 
    } else {
        printf("Отлично, работаем с числом %d.\n\n", number);
    }

    // 2. Цикл for (Инициализация; Условие продолжения; Шаг)
    printf("Анализ чисел до вашего:\n");
    for (int i = 1; i <= number; i++) {
        // Проверяем остаток от деления на 2, чтобы узнать, четное ли число
        if (i % 2 == 0) {
            printf("%d - четное\n", i);
        } else {
            printf("%d - нечетное\n", i);
        }
    }

    // 3. Цикл while
    printf("\nОбратный отсчет:\n");
    int count = number;
    
    while (count > 0) {
        printf("%d... ", count);
        count--; // Это то же самое, что count = count - 1
    }
    printf("Пуск!\n");

    return 0; // Программа завершилась успешно
}