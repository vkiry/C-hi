#include <stdio.h>

int main() {
    // 1. Массив целых чисел
    // Указываем размер [5] и сразу задаем значения
    int scores[5] = {85, 90, 78, 92, 88};
    int sum = 0;

    printf("--- Обработка массива ---\n");
    // Цикл for идеально подходит для перебора массивов
    for (int i = 0; i < 5; i++) {
        printf("Оценка %d: %d\n", i + 1, scores[i]);
        sum += scores[i]; // Аналог sum = sum + scores[i]
    }
    
    // Преобразуем sum в float перед делением, чтобы получить дробный результат
    printf("Средний балл: %.2f\n\n", (float)sum / 5);


    // 2. Строки (массивы символов)
    printf("--- Работа со строками ---\n");
    // Пустые скобки [] означают, что компилятор сам посчитает длину (12 символов + '\0')
    char tool_name[] = "Command Line"; 
    
    // Спецификатор %s выводит массив символов до тех пор, пока не встретит '\0'
    printf("Любимый инструмент: %s\n", tool_name);
    
    // Доступ к отдельному символу (выведет 'C')
    printf("Первая буква: %c\n", tool_name[0]);

    // Посчитаем длину строки вручную, ища '\0'
    int length = 0;
    while (tool_name[length] != '\0') {
        length++;
    }
    printf("Длина строки: %d символов\n", length);

    return 0;
}